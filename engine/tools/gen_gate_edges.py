"""Regenerate the compiled silhouette bank from the saved contour assets."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
bank = json.loads((root / 'resources_product/gate_edges/profiles.json').read_text())
assert bank['version'] == 1 and bank['samples'] == 1024
rows = bank['profiles']
assert {r['side'] for r in rows} == set(range(4))
lines = ['// Generated by engine/tools/gen_gate_edges.py; see resources_product/gate_edges/README.md.',
         '#pragma once', 'namespace spk {', 'constexpr int kMeasuredGateSamples = 1024;',
         'struct MeasuredGateEdge { int side; float offset[1024]; };',
         'constexpr MeasuredGateEdge kMeasuredGateEdges[] = {']
for row in rows:
    values = row['offsets_mm']
    assert len(values) == 1024 and all(-.5 < x < .5 for x in values)
    assert abs(values[0]) < 1e-5 and abs(values[-1]) < 1e-5
    lines.append('{' + str(row['side']) + ', {' + ','.join(f'{x:.6f}f' for x in values) + '}},')
lines += ['};', '} // namespace spk']
(root / 'src/pipeline/gate_edges.h').write_text('\n'.join(lines) + '\n')
